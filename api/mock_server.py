ERROR = {"code": "error", "message": "", "details": []}


def err(code, message):
    e = dict(ERROR)
    e["code"] = {400: "bad_request", 401: "unauthorized", 404: "not_found",
                 405: "method_not_allowed"}.get(code, "error")
    e["message"] = message
    return code, e


def resolve(method, path, headers):
    matched = None
    path_found = False
    for r in MOCK_ROUTES:
        pattern = "^" + re.sub(r"\{[^}]+\}", r"[^/]+", r["template"]) + "$"
        if re.match(pattern, path):
            path_found = True
            if r["method"] == method:
                matched = r
                break
    if not path_found:
        return err(404, "Маршрут не найден в спецификации OpenAPI")
    if matched is None:
        return err(405, "HTTP-метод не определён для данного маршрута")
    if matched["jwt"] and not str(headers.get("Authorization", "")).startswith("Bearer "):
        return err(401, "Отсутствует или недействителен JWT-токен")
    if matched["hmac"] and not headers.get("X-Webhook-Signature"):
        return err(401, "Отсутствует HMAC-подпись webhook")
    if "999999" in path:
        return err(404, "Ресурс не найден")
    return matched["status"], matched["body"]


class Handler(BaseHTTPRequestHandler):
    def _handle(self):
        from urllib.parse import urlparse
        path = urlparse(self.path).path.rstrip("/") or "/"
        length = int(self.headers.get("Content-Length", 0) or 0)
        if length:
            self.rfile.read(length)
        code, body = resolve(self.command, path, self.headers)
        data = b"" if body is None else json.dumps(body, ensure_ascii=False).encode("utf-8")
        self.send_response(code)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        if data:
            self.wfile.write(data)

    do_GET = do_POST = do_PUT = do_PATCH = do_DELETE = _handle

    def log_message(self, fmt, *args):
        pass


if __name__ == "__main__":
    port = int(sys.argv[1]) if len(sys.argv) > 1 else 8080
    print("КнигаМаг Mock API: http://localhost:%d" % port)
    HTTPServer(("127.0.0.1", port), Handler).serve_forever()
